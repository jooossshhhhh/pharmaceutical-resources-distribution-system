do $verify$
declare
  v_updated_count integer;
  v_null_cost_count integer;
begin
  select count(*) into v_updated_count
  from public.medicines
  where unit_cost is not null and unit_cost > 0;

  select count(*) into v_null_cost_count
  from public.medicines
  where unit_cost is null or unit_cost <= 0;

  if v_updated_count <> 191 then
    raise exception 'Expected 191 medicines to have valid unit_cost, found %.', v_updated_count;
  end if;

  if v_null_cost_count <> 0 then
    raise exception 'Found % medicines with null or non-positive unit_cost.', v_null_cost_count;
  end if;
end
